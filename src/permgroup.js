// Small permutation groups, as explicit lists of elements.
//
// A permutation of {0, …, n−1} is an array p with p[i] the image of i. Groups
// here are the Galois groups of polynomials of small degree (at most a few
// thousand elements), so every group is stored by its elements.

/** a∘b: first b, then a. */
export const compose = (a, b) => b.map((x) => a[x]);
export const inverse = (a) => {
  const out = Array(a.length);
  a.forEach((x, i) => { out[x] = i; });
  return out;
};
export const identity = (n) => Array.from({ length: n }, (_, i) => i);
const key = (a) => a.join(",");

/** The cycles of a permutation, longest first; fixed points are left out unless `all`. */
export function cycles(p, { all = false } = {}) {
  const seen = Array(p.length).fill(false);
  const out = [];
  for (let i = 0; i < p.length; i += 1) {
    if (seen[i]) continue;
    const c = [];
    for (let j = i; !seen[j]; j = p[j]) { seen[j] = true; c.push(j); }
    if (all || c.length > 1) out.push(c);
  }
  return out;
}

/** The cycle type, a partition of n such as [3, 2, 1, 1]. */
export const cycleType = (p) => cycles(p, { all: true }).map((c) => c.length).sort((a, b) => b - a);

/** Cycle notation counted from 1: "(1 2 3)(4 5)", and "()" for the identity. */
export function cycleString(p) {
  const cs = cycles(p);
  return cs.length ? cs.map((c) => `(${c.map((x) => x + 1).join(" ")})`).join("") : "()";
}

/** Reads "(1 2 3)(4 5)" as a permutation of n points. */
export function fromCycles(text, n) {
  const p = identity(n);
  for (const m of String(text).matchAll(/\(([^)]*)\)/g)) {
    const c = m[1].trim().split(/[\s,]+/).filter(Boolean).map((s) => Number(s) - 1);
    if (c.some((x) => !Number.isInteger(x) || x < 0 || x >= n)) throw new RangeError(`cycle ${m[0]} does not fit ${n} points`);
    c.forEach((x, i) => { p[x] = c[(i + 1) % c.length]; });
  }
  return p;
}

export const isEven = (p) => cycles(p).reduce((s, c) => s + c.length - 1, 0) % 2 === 0;

export function order(p) {
  const g = (a, b) => (b ? g(b, a % b) : a);
  return cycleType(p).reduce((l, c) => (l * c) / g(l, c), 1);
}

function closure(gens, n, cap = Infinity) {
  const id = identity(n);
  const seen = new Map([[key(id), id]]);
  const queue = [id];
  while (queue.length) {
    const g = queue.pop();
    for (const s of gens) {
      const h = compose(s, g);
      const k = key(h);
      if (seen.has(k)) continue;
      seen.set(k, h);
      queue.push(h);
      if (seen.size > cap) throw new RangeError(`a group of more than ${cap} elements`);
    }
  }
  return seen;
}

function allPermutations(n) {
  const out = [];
  const rec = (a, rest) => {
    if (!rest.length) { out.push(a); return; }
    rest.forEach((x, i) => rec([...a, x], [...rest.slice(0, i), ...rest.slice(i + 1)]));
  };
  rec([], identity(n));
  return out;
}

const subsets = (n, k) => {
  const out = [];
  const rec = (s, a) => {
    if (a.length === k) { out.push(a); return; }
    for (let i = s; i < n; i += 1) rec(i + 1, [...a, i]);
  };
  rec(0, []);
  return out;
};
export { subsets, allPermutations };

export class PermGroup {
  #map;
  #classes = null;
  #subgroups = null;

  /** The group generated by the given permutations of n points. */
  constructor(generators, n = generators[0]?.length, { maxOrder = 50000 } = {}) {
    if (!Number.isInteger(n) || n < 1) throw new RangeError("a permutation group needs its degree");
    for (const g of generators) {
      if (g.length !== n || [...g].sort((a, b) => a - b).some((x, i) => x !== i)) throw new RangeError(`[${g}] is not a permutation of ${n} points`);
    }
    this.degree = n;
    this.generators = generators.map((g) => [...g]);
    this.#map = closure(this.generators, n, maxOrder);
    this.elements = [...this.#map.values()].sort((a, b) => order(a) - order(b) || (key(a) < key(b) ? -1 : 1));
    this.order = this.elements.length;
  }

  static symmetric(n) {
    return new PermGroup(n === 1 ? [] : n === 2 ? [[1, 0]] : [[1, 0, ...identity(n).slice(2)], [...identity(n).slice(1), 0]], n);
  }

  static alternating(n) {
    const gens = [];
    for (let i = 2; i < n; i += 1) {
      const p = identity(n);
      p[0] = 1; p[1] = i; p[i] = 0;
      gens.push(p);
    }
    return new PermGroup(gens, n);
  }

  /** From cycle notation: PermGroup.from(["(1 2 3 4)", "(1 3)"], 4). */
  static from(texts, n) {
    return new PermGroup(texts.map((t) => (Array.isArray(t) ? t : fromCycles(t, n))), n);
  }

  has(p) { return this.#map.has(key(p)); }
  contains(H) { return H.degree === this.degree && H.generators.every((g) => this.has(g)); }
  equals(H) { return H.order === this.order && this.contains(H); }
  get isTransitive() { return this.orbits().length === 1; }
  get isAbelian() { return this.generators.every((a) => this.generators.every((b) => key(compose(a, b)) === key(compose(b, a)))); }
  get isCyclic() { return this.elements.some((g) => order(g) === this.order); }
  get isEven() { return this.generators.every(isEven); }

  /** Orbits on the points. */
  orbits() {
    const seen = Array(this.degree).fill(false);
    const out = [];
    for (let i = 0; i < this.degree; i += 1) {
      if (seen[i]) continue;
      const orb = [...new Set(this.elements.map((g) => g[i]))].sort((a, b) => a - b);
      orb.forEach((x) => { seen[x] = true; });
      out.push(orb);
    }
    return out;
  }

  /** Orbits on the k-element subsets, each a list of sorted subsets. */
  orbitsOnSets(k) {
    const S = subsets(this.degree, k);
    const index = new Map(S.map((s, i) => [key(s), i]));
    const seen = Array(S.length).fill(false);
    const out = [];
    for (let i = 0; i < S.length; i += 1) {
      if (seen[i]) continue;
      const orb = [];
      for (const g of this.elements) {
        const j = index.get(key(S[i].map((x) => g[x]).sort((a, b) => a - b)));
        if (!seen[j]) { seen[j] = true; orb.push(S[j]); }
      }
      out.push(orb);
    }
    return out;
  }

  /** How many elements have each cycle type: [{ type: [2, 1, 1], count, share }] with share = count/order. */
  cycleTypes() {
    const counts = new Map();
    for (const g of this.elements) {
      const t = cycleType(g).join(",");
      counts.set(t, (counts.get(t) || 0) + 1);
    }
    return [...counts].map(([t, count]) => ({ type: t.split(",").map(Number), count, share: count / this.order }))
      .sort((a, b) => b.count - a.count || (a.type.join() < b.type.join() ? -1 : 1));
  }

  /** The subgroup generated by some elements of this group. */
  subgroup(generators) {
    const gens = generators.map((g) => (typeof g === "string" ? fromCycles(g, this.degree) : g));
    for (const g of gens) if (!this.has(g)) throw new RangeError(`${cycleString(g)} is not in the group`);
    return new PermGroup(gens, this.degree);
  }

  /** g·H·g⁻¹. */
  conjugate(H, g) {
    const gi = inverse(g);
    return new PermGroup(H.generators.map((h) => compose(g, compose(h, gi))), this.degree);
  }

  isNormal(H) {
    return this.generators.every((g) => {
      const gi = inverse(g);
      return H.generators.every((h) => H.has(compose(g, compose(h, gi))));
    });
  }

  /** One element from each left coset g·H. */
  cosets(H) {
    const seen = new Set();
    const reps = [];
    for (const g of this.elements) {
      if (seen.has(key(g))) continue;
      reps.push(g);
      for (const h of H.elements) seen.add(key(compose(g, h)));
    }
    return reps;
  }

  /** The subgroup generated by all commutators: the normal closure of the generators' commutators. */
  derivedSubgroup() {
    const comm = (a, b) => compose(compose(a, b), compose(inverse(a), inverse(b)));
    let gens = [];
    const seen = new Set([key(identity(this.degree))]);
    const push = (c) => { if (!seen.has(key(c))) { seen.add(key(c)); gens.push(c); } };
    for (const a of this.generators) for (const b of this.generators) push(comm(a, b));
    let H = new PermGroup(gens, this.degree);
    for (;;) {
      const extra = [];
      for (const g of this.generators) {
        const gi = inverse(g);
        for (const h of H.generators) {
          const c = compose(g, compose(h, gi));
          if (!H.has(c)) extra.push(c);
        }
      }
      if (!extra.length) break;
      gens = [...H.generators, ...extra];
      H = new PermGroup(gens, this.degree);
    }
    return H.withSmallGenerators();
  }

  /** G ⊇ G′ ⊇ G″ ⊇ …, until it repeats. Ends in the trivial group exactly when the group is solvable. */
  derivedSeries() {
    const out = [this];
    for (;;) {
      const next = out[out.length - 1].derivedSubgroup();
      if (next.order === out[out.length - 1].order) return out;
      out.push(next);
    }
  }

  get isSolvable() {
    const s = this.derivedSeries();
    return s[s.length - 1].order === 1;
  }

  /** The same group with few generators (chosen greedily). */
  withSmallGenerators() {
    if (this.generators.length <= 2) return this;
    const pick = [];
    let size = 1;
    let H = new PermGroup([], this.degree);
    while (size < this.order) {
      let best = null;
      for (const g of [...this.elements].reverse()) {
        if (H.has(g)) continue;
        const K = new PermGroup([...pick, g], this.degree);
        if (!best || K.order > best.K.order) best = { g, K };
        if (best.K.order === this.order) break;
      }
      pick.push(best.g);
      H = best.K;
      size = H.order;
    }
    return H;
  }

  /** Every subgroup. Refuses groups of more than `maxOrder` elements (default 400). */
  subgroups({ maxOrder = 400 } = {}) {
    if (this.#subgroups) return this.#subgroups;
    if (this.order > maxOrder) throw new RangeError(`listing all subgroups of a group of order ${this.order} is too much work (maxOrder ${maxOrder})`);
    // work with element numbers and a multiplication table
    const E = this.elements;
    const N = E.length;
    const number = new Map(E.map((g, i) => [key(g), i]));
    const table = E.map((g) => Uint16Array.from(E, (h) => number.get(key(compose(g, h)))));
    const e = number.get(key(identity(this.degree)));
    const generate = (gens) => {
      const inside = new Uint8Array(N);
      inside[e] = 1;
      const queue = [e];
      const list = [e];
      while (queue.length) {
        const x = queue.pop();
        for (const s of gens) {
          const y = table[s][x];
          if (!inside[y]) { inside[y] = 1; queue.push(y); list.push(y); }
        }
      }
      return { gens, inside, id: list.sort((u, v) => u - v).join(",") };
    };
    const cyclic = new Map();
    for (let i = 0; i < N; i += 1) {
      if (i === e) continue;
      const C = generate([i]);
      if (!cyclic.has(C.id)) cyclic.set(C.id, i);
    }
    const trivial = generate([]);
    const found = new Map([[trivial.id, trivial]]);
    let layer = [trivial];
    while (layer.length) {
      const next = [];
      for (const H of layer) {
        for (const g of cyclic.values()) {
          if (H.inside[g]) continue;
          const K = generate([...H.gens, g]);
          if (found.has(K.id)) continue;
          found.set(K.id, K);
          next.push(K);
        }
      }
      layer = next;
    }
    this.#subgroups = [...found.values()].map((H) => new PermGroup(H.gens.map((i) => E[i]), this.degree)).sort((x, y) => x.order - y.order);
    return this.#subgroups;
  }

  /**
   * Subgroups up to conjugacy: [{ group, order, index, conjugates, normal }],
   * smallest first. `conjugates` is the number of subgroups in the class.
   */
  subgroupClasses(options) {
    if (this.#classes) return this.#classes;
    const sig = (H) => H.elements.map(key).sort().join("|");
    const seen = new Set();
    const out = [];
    for (const H of this.subgroups(options)) {
      if (seen.has(sig(H))) continue;
      const cls = new Set();
      for (const g of this.elements) {
        const gi = inverse(g);
        cls.add(H.elements.map((h) => key(compose(g, compose(h, gi)))).sort().join("|"));
      }
      cls.forEach((s) => seen.add(s));
      out.push({ group: H, order: H.order, index: this.order / H.order, conjugates: cls.size, normal: cls.size === 1 });
    }
    this.#classes = out;
    return out;
  }

  toString() {
    return this.generators.length ? `⟨${this.generators.map(cycleString).join(", ")}⟩` : "⟨⟩";
  }
}
